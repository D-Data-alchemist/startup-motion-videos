"""
Copies only the Noto Sans SC slices that contain CJK characters used in src/ into public/fonts/cjk
and writes src/cjk-fonts.ts. Re-run after changing any Chinese text:  python3 scripts/prepare_fonts.py
"""
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / 'node_modules' / '@fontsource' / 'noto-sans-sc'
OUT = ROOT / 'public' / 'fonts' / 'cjk'
WEIGHTS = ['400', '700', '900']

chars = set()
for f in (ROOT / 'src').rglob('*.tsx'):
    chars |= {ord(c) for c in f.read_text() if '⺀' <= c <= '鿿' or '＀' <= c <= '￯' or '　' <= c <= '〿'}


def covers(rng):
    for part in rng.split(','):
        part = part.strip().removeprefix('U+')
        a, _, b = part.partition('-')
        if '?' in a:
            lo, hi = int(a.replace('?', '0'), 16), int(a.replace('?', 'F'), 16)
        else:
            lo, hi = int(a, 16), int(b or a, 16)
        if any(lo <= c <= hi for c in chars):
            return True
    return False


if OUT.exists():
    shutil.rmtree(OUT)
OUT.mkdir(parents=True)
entries = []
for w in WEIGHTS:
    css = (PKG / f'{w}.css').read_text()
    for block in css.split('@font-face')[1:]:
        file = re.search(r"url\(\./files/([^)]+-normal\.woff2)\)", block).group(1)
        rng = re.search(r'unicode-range:\s*([^;]+);', block).group(1)
        if covers(rng):
            shutil.copy(PKG / 'files' / file, OUT / file)
            entries.append((file, w, rng.strip()))

lines = ',\n'.join(f"  {{file: '{f}', weight: '{w}', range: '{r}'}}" for f, w, r in entries)
(ROOT / 'src' / 'cjk-fonts.ts').write_text(
    '// Generated by scripts/prepare_fonts.py — Noto Sans SC slices covering the Chinese text in this video\n'
    f'export const CJK_FONT_FILES: {{file: string; weight: string; range: string}}[] = [\n{lines},\n];\n'
)
print(f'{len(chars)} CJK chars → {len(entries)} font slices')
